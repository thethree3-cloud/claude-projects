"""Write SCENARIOS.md: every scenario, its expectations, and today's detector
result, for a human to read and approve before any paid eval run.

    python evals/review_scenarios.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import grade  # noqa: E402
import scenarios as S  # noqa: E402

OUT = Path(__file__).parent / "SCENARIOS.md"


def fence(text):
    ticks = "`" * max(3, max((len(r) for r in text.split("\n") for r in [r] if set(r) == {"`"}), default=0) + 1)
    return f"{ticks}text\n{text}\n{ticks}"


def main():
    lines = ["# Eval scenarios (for review)", "",
             "Fictional machines with hand-written expectations. Generated by "
             "`evals/review_scenarios.py` from `evals/scenarios.py`; edit that file, not this one.", "",
             "| # | id | tags | expected findings | Claude checks | detector today |", "|---|---|---|---|---|---|"]
    details = []
    for n, s in enumerate(S.SCENARIOS, 1):
        snap, findings, _ = S.build(s)
        d = grade.grade_detector(s, findings)
        ok = "pass" if d["grade"]["pass"] else "**FAIL**"
        c = s.get("claude", {})
        checks = ", ".join(k for k in ("first", "injection", "calm") if c.get(k)) or "-"
        lines.append(f"| {n} | `{s['id']}` | {', '.join(s['tags'])} | {len(s.get('expect', []))} | {checks} | {ok} |")

        details += [f"## {n}. `{s['id']}`", "", s["description"], ""]
        if s.get("expect"):
            details.append("Must find (rule, subject contains, severity):")
            details += [f"- `{r}` · \"{p}\" · **{sev}**" for r, p, sev in s["expect"]]
        else:
            details.append("Must find: nothing.")
        if "max_severity" in s:
            details.append(f"\nWorst severity allowed: **{s['max_severity'] or 'none at all'}**")
        if c.get("first"):
            details.append(f"\nClaude: priority-1 group must include one of {', '.join(f'`{x}`' for x in c['first'])}")
        if c.get("injection"):
            details.append(f"\nClaude: must keep the finding containing \"{c['injection']}\" at high and not call the machine safe")
        if c.get("calm"):
            details.append("\nClaude: summary must not sound alarming")
        details += ["", f"Detector today: {ok}. It reports {len(findings)} finding(s):", "",
                    fence("\n".join(f"{f['severity']:6} {f['check']:26} {f['subject']}" for f in findings) or "(none)")]
        if d["missed"] or d["wrong_severity"] or d["alarms"]:
            details.append("")
            details += [f"- missed: `{r}` \"{p}\" ({sev})" for r, p, sev in d["missed"]]
            details += [f"- wrong severity: `{r}` \"{p}\" expected {e}, got {g}" for r, p, e, g in d["wrong_severity"]]
            details += [f"- false alarm: {a}" for a in d["alarms"]]
        details.append("")

    OUT.write_text("\n".join(lines + [""] + details), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
